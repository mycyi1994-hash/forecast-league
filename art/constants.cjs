// Writes src/CardArtConstants.sol and src/CardArtData.sol from the reference implementation in
// card.cjs. Both files are pure data: palettes, per-tier numbers and the per-tier SVG fragments
// whose coordinates need trigonometry (rings, rays) and are therefore computed here, once.
const fs = require('fs');
const path = require('path');
const { TC, SP, PAL, TIER, stops } = require('./card.cjs');

const lit = s => { if (s.includes("'") || s.includes('\\')) throw new Error('unexpected character in constant'); return `'${s}'`; };
function byTier(name, values, type = 'string memory') {
  const body = values.map((v, i) => (i < 3 ? `        if (ti == ${i}) return ${v};\n` : `        return ${v};\n`)).join('');
  return `    function ${name}(uint256 ti) internal pure returns (${type}) {\n${body}    }\n`;
}
const OFF_M = ['0', '.28', '.5', '.72', '1'], OFF_P = ['0', '.22', '.5', '.8', '1'];

function byTierExt(name, values) {
  const body = values.map((v, i) => (i < 3 ? `        if (ti == ${i}) return ${v};\n` : `        return ${v};\n`)).join('');
  return `    function ${name}(uint256 ti) external pure returns (string memory) {\n${body}    }\n`;
}

// Small values, inherited by CardArt.
const out = `// SPDX-License-Identifier: MIT
pragma solidity 0.8.28;

/// @title CardArtConstants
/// @notice Small per-tier values and the colour palettes of the player card.
/// @dev Generated by art/constants.cjs from art/card.cjs. Do not edit by hand.
abstract contract CardArtConstants {
    /// @dev 8 palettes x 4 colours (deep, mid, bright, accent) x 6 hex characters.
    bytes internal constant PALETTE = ${lit(PAL.map(p => p.join('')).join(''))};

${byTier('_tierName', TIER.map(t => lit(t.n)))}
${byTier('_frame', TIER.map(t => String(t.f)), 'uint256')}
${byTier('_radius', TIER.map(t => String(t.r)), 'uint256')}
${byTier('_blobOpacity', TIER.map(t => lit(t.bo)))}
${byTier('_glowOpacity', TIER.map(t => lit(t.glow)))}
${byTier('_highlightOpacity', TIER.map(t => lit(t.hl)))}
${byTier('_pedestalGlow', TIER.map(t => lit(t.ped)))}}
`;

// Large SVG fragments, deployed as their own contract so that CardArt stays under the size limit.
const data = `// SPDX-License-Identifier: MIT
pragma solidity 0.8.28;

/// @title CardArtData
/// @notice The SVG fragments of the player card that are fixed for each tier: metal gradients,
///         orbit rings, light rays and sparkles. \`ti\` is the tier, 0 (ROOKIE) to 3 (ORACLE).
/// @dev Generated by art/constants.cjs from art/card.cjs. Do not edit by hand.
///      No state, no owner, nothing payable. It exists only because the art does not fit
///      into one contract.
contract CardArtData {
    /// @notice Gradient stops of the frame metal, corner to corner.
${byTierExt('metal', TIER.map(t => lit(stops(t.m, OFF_M))))}
    /// @notice The same metal arranged left to right, for the round pedestal.
${byTierExt('metalRound', TIER.map(t => lit(stops([t.m[0], t.m[3], t.m[2], t.m[1], t.m[4]], OFF_P))))}
    /// @notice Orbit rings: the part drawn behind the orb.
${byTierExt('ringsBack', TC.map(x => lit(x.back)))}
    /// @notice Orbit rings: the part drawn in front of the orb, with one satellite per ring.
${byTierExt('ringsFront', TC.map(x => lit(x.front)))}
    /// @notice Twelve light rays from the orb's centre. Empty for the two lowest tiers.
${byTierExt('rays', TC.map(x => lit(x.rays)))}
    /// @notice Sparkles. Tier 1 shows group 0, tier 2 groups 0-1, tier 3 groups 0-2.
    function sparkles(uint256 ti) external pure returns (string memory) {
        if (ti == 0) return "";
        if (ti == 1) return _group0();
        if (ti == 2) return string.concat(_group0(), _group1());
        return string.concat(_group0(), _group1(), _group2());
    }

    function _group0() private pure returns (string memory) {
        return ${lit(SP[0])};
    }

    function _group1() private pure returns (string memory) {
        return ${lit(SP[1])};
    }

    function _group2() private pure returns (string memory) {
        return ${lit(SP[2])};
    }
}
`;
fs.writeFileSync(path.join(__dirname, '..', 'src', 'CardArtData.sol'), data);
fs.writeFileSync(path.join(__dirname, '..', 'src', 'CardArtConstants.sol'), out);
console.log('wrote src/CardArtConstants.sol', out.length, 'bytes and src/CardArtData.sol', data.length, 'bytes');
